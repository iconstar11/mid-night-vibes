"""Top picks from the ratings workbook: the owner's rating counts double, Claude's breaks ties.

    .venv/Scripts/python scripts/top_picks_from_ratings.py

Reads data/card-ratings.xlsx (Truths, Dares, Spin the Wheel sheets) and writes mobile/src/game/topPicks.ts:
the best 3 truths and dares per deck and heat (girls'/boys' extras: the best 1) and the best 2 wedges per wheel
and heat. Cards rewritten since the ratings (their id changed) are left out until they're rated again.
Later, real play data takes over: scripts/cards_to_excel.py + import_top_picks.py.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
HEATS = {"Flirty": 1, "Steamy": 2, "Spicy": 3}
DECKS = {"Couple": "couple", "Group (all)": "group", "Girls' night": "girls", "Boys' night": "boys"}


def main() -> None:
    subprocess.run(["node", "--no-warnings", "scripts/dump_cards.mts"], cwd=ROOT / "mobile", check=True, capture_output=True)
    cards = {c["id"]: c for c in json.loads((ROOT / "data/cards.json").read_text(encoding="utf8"))}
    rows = []
    for sheet, typ in [("Truths", "truth"), ("Dares", "dare"), ("Spin the Wheel", "wedge")]:
        d = pd.read_excel(ROOT / "data/card-ratings.xlsx", sheet_name=sheet)
        d = d[d["id"].isin(cards.keys()) & d["your_rating"].notna()]
        d = d.assign(type=typ, deck=d["deck"].map(DECKS), heat=d["heat"].map(HEATS).fillna(0).astype(int),
                     score=d["your_rating"] * 2 + d["claude_rating"])
        rows.append(d[d["decision"].astype("string").fillna("").str.lower() != "remove"])
    r = pd.concat(rows)
    picks = []
    for (deck, typ, heat), g in r.groupby(["deck", "type", "heat"]):
        n = 2 if typ == "wedge" else 1 if deck in ("girls", "boys") else 3
        picks += g.sort_values(["score", "your_rating"], ascending=False).head(n).to_dict("records")
    picks.sort(key=lambda p: p["id"])
    lines = [f'  "{p["id"]}", // {"wheel" if p["type"] == "wedge" else "tod"} {p["deck"]} {p["type"]} h{p["heat"]}: {cards[p["id"]]["text"]}' for p in picks]
    (ROOT / "mobile/src/game/topPicks.ts").write_text(
        "// Top picks: the best cards, shown first in every session (and so in guests' free turns).\n"
        "// GENERATED by scripts/top_picks_from_ratings.py from data/card-ratings.xlsx (owner's rating x2 + Claude's).\n"
        "export const TOP_PICKS: ReadonlySet<string> = new Set([\n" + "\n".join(lines) + "\n]);\n",
        encoding="utf8",
    )
    print(f"{len(picks)} top picks written")


if __name__ == "__main__":
    main()
