"""Put the new cards (data/new-cards.xlsx) into the game: writes them into mobile/src/game/content.ts between the
<new-cards> markers (not a separate file: scripts/dump_cards.mts loads content.ts with plain Node), where they're merged in.

    .venv/Scripts/python scripts/predict_ratings.py    # first: predicted_rating from the owner's last review
    .venv/Scripts/python scripts/import_new_cards.py

Which cards go in:
  - your decision "remove"          -> out
  - your_rating filled in           -> in at 3 or more (your rating wins)
  - otherwise                       -> in when predicted_rating is 3.8 or more
  - decision "change" with a rewrite -> the rewrite goes in instead of the text
Wheel and Misfortune sections have a text per heat: a section goes in when the average of its three is high enough.
Run it again after you review the workbook; it rewrites that block from scratch.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from predict_ratings import KEEP_AT

ROOT = Path(__file__).resolve().parent.parent
NEW = ROOT / "data" / "new-cards.xlsx"
OUT = ROOT / "mobile" / "src" / "game" / "content.ts"
START, END = "// <new-cards>", "// </new-cards>"
HEAT = {"Flirty": 0, "Steamy": 1, "Spicy": 2}


def score(r) -> float:
    if str(r.get("decision") or "").strip().lower() == "remove":
        return -1
    if pd.notna(r.get("your_rating")):
        return 5 if r["your_rating"] >= 3 else 0  # your rating decides
    return float(r["predicted_rating"])


def text_of(r) -> str:
    if str(r.get("decision") or "").strip().lower() == "change" and pd.notna(r.get("rewrite")) and str(r["rewrite"]).strip():
        return str(r["rewrite"]).strip()
    return str(r["text"]).strip()


def main() -> None:
    existing = {c["text"] for c in json.loads((ROOT / "data" / "cards.json").read_text(encoding="utf8"))}
    deck: dict[str, dict[str, list[list[str]]]] = {}
    counts = {"truth": 0, "dare": 0, "wheel": 0, "misfortune": 0}
    for sheet, kind in [("Truths", "truth"), ("Dares", "dare")]:
        for _, r in pd.read_excel(NEW, sheet_name=sheet).iterrows():
            t = text_of(r)
            if score(r) < KEEP_AT or t in existing:
                continue
            d = deck.setdefault(r["deck"], {"truth": [[], [], []], "dare": [[], [], []]})
            d[kind][HEAT[r["heat"]]].append(t)
            counts[kind] += 1
    wheels: dict[str, dict[str, list]] = {"wheel": {"couple": [], "group": []}, "misfortune": {"couple": [], "group": []}}
    for sheet, kind in [("Spin the Wheel", "wheel"), ("Misfortune", "misfortune")]:
        d = pd.read_excel(NEW, sheet_name=sheet)
        for (deck_id, label), g in d.groupby(["deck", "wedge"], sort=False):
            g = g.sort_values("heat", key=lambda s: s.map(HEAT))
            scores = [score(r) for _, r in g.iterrows()]
            if len(g) != 3 or min(scores) < 0 or sum(scores) / 3 < KEEP_AT:
                continue
            wheels[kind][deck_id].append([str(label), [text_of(r) for _, r in g.iterrows()]])
            counts[kind] += 1

    js = lambda v: json.dumps(v, ensure_ascii=False, indent=1)
    src = OUT.read_text(encoding="utf8")
    a, b = src.index(START), src.index(END) + len(END)
    OUT.write_text(
        src[:a]
        + f"{START}\n// GENERATED by scripts/import_new_cards.py from data/new-cards.xlsx: edit the workbook, not this block.\n"
        + f"const NEW_DECK: Record<string, Record<CardType, string[][]>> = {js(deck)};\n"
        + f"const NEW_WHEELS: Record<\"couple\" | \"group\", Wedge[]> = {js(wheels['wheel'])};\n"
        + f"const NEW_MISFORTUNE: Record<\"couple\" | \"group\", Wedge[]> = {js(wheels['misfortune'])};\n{END}"
        + src[b:],
        encoding="utf8",
    )
    print(f"{OUT.relative_to(ROOT)}: {counts['truth']} truths, {counts['dare']} dares, "
          f"{counts['wheel']} wheel sections, {counts['misfortune']} misfortune sections")


if __name__ == "__main__":
    main()
