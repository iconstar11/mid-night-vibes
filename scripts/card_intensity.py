def main() -> None:
    cards = [c for c in json.loads((ROOT / "data" / "cards.json").read_text(encoding="utf8")) if c["game"] == "tod"]
    mine = {}
    if XLSX.exists():  # keep the owner's scores
        old = pd.read_excel(XLSX)
        mine = {r.id: int(r.your_intensity) for r in old.itertuples() if pd.notna(r.your_intensity) and 1 <= r.your_intensity <= 5}
    rows, scores = [], {}
    for c in sorted(cards, key=lambda c: (c["group"], c["type"], c["heat"], CLAUDE.get(c["id"], 3))):
        claude = CLAUDE.get(c["id"])
        scores[c["id"]] = mine.get(c["id"], claude or 3)
        rows.append({"deck": c["group"], "type": c["type"], "heat": c["heat"], "text": c["text"],
                     "claude_intensity": claude, "your_intensity": mine.get(c["id"]), "id": c["id"]})
    missing = [r["text"] for r in rows if r["claude_intensity"] is None]
    pd.DataFrame(rows).to_excel(XLSX, index=False)
    lines = [f'  "{k}": {v},' for k, v in sorted(scores.items())]
    OUT.write_text(
        "// How bold each built-in card is inside its heat level (1 mild … 5 boldest); unknown cards count as 3.\n"
        "// GENERATED by scripts/card_intensity.py from data/card-intensity.xlsx: edit the workbook, not this file.\n"
        "export const INTENSITY: Readonly<Record<string, number>> = {\n" + "\n".join(lines) + "\n};\n",
        encoding="utf8",
    )
    print(f"{len(scores)} cards scored ({len(mine)} by you) -> {OUT.relative_to(ROOT)}, {XLSX.relative_to(ROOT)}")
    if missing:
        print(f"{len(missing)} cards have no score yet (counted as 3):", *missing[:10], sep="\n  ")


if __name__ == "__main__":
    main()
