"""Read data/card-review.xlsx and update the app:
  Cards sheet, top_pick = yes       -> mobile/src/game/topPicks.ts (shown first in every session)
  AI cards sheet, add_to_deck = yes -> mobile/src/game/promoted.ts (AI cards that become built-in cards)

Run from the repo root after editing the sheet:
    .venv/Scripts/python scripts/import_top_picks.py
"""
import argparse
import json
import subprocess
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SHEET = ROOT / "data" / "card-review.xlsx"
YES = {"yes", "y", "x", "1", "true"}
DECKS = {"couple", "group", "girls", "boys"}


def write_promoted(rows: pd.DataFrame) -> int:
    items = []
    for r in rows.itertuples():
        text, deck, typ = str(r.text).strip(), str(r.deck).strip(), str(r.type).strip()
        heat = int(float(r.heat)) if str(r.heat).strip() else 1
        if not text or deck not in DECKS or typ not in ("truth", "dare") or heat not in (1, 2, 3):
            print(f"  skipped (check deck/type/heat): {text[:60]}")
            continue
        items.append(f"  {{ text: {json.dumps(text, ensure_ascii=False)}, deck: \"{deck}\", type: \"{typ}\", heat: {heat} }},")
    body = "\n".join(items)
    (ROOT / "mobile/src/game/promoted.ts").write_text(
        "// AI cards promoted into the built-in deck (they play like any other built-in card from now on).\n"
        "// GENERATED by scripts/import_top_picks.py from the \"AI cards\" sheet of data/card-review.xlsx (add_to_deck = yes).\n"
        'import type { CardType } from "./types";\n\n'
        'export type Promoted = { text: string; deck: "couple" | "group" | "girls" | "boys"; type: CardType; heat: 1 | 2 | 3 };\n\n'
        f"export const PROMOTED: Promoted[] = [\n{body}\n];\n",
        encoding="utf8",
    )
    return len(items)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", type=Path, default=SHEET, help="review workbook to read (default data/card-review.xlsx)")
    sheet = ap.parse_args().sheet
    cards = pd.read_excel(sheet, sheet_name="Cards", dtype=str).fillna("")
    picks = cards[cards["top_pick"].str.strip().str.lower().isin(YES)]
    subprocess.run(
        ["node", "--no-warnings", "scripts/write_top_picks.mts"],
        cwd=ROOT / "mobile", input=json.dumps(sorted(set(picks["id"]))), text=True, check=True,
    )
    print(picks.groupby(["game", "group", "type"]).size().to_string())

    try:
        ai = pd.read_excel(sheet, sheet_name="AI cards", dtype=str).fillna("")
    except ValueError:
        ai = pd.DataFrame(columns=["add_to_deck"])
    n = write_promoted(ai[ai["add_to_deck"].str.strip().str.lower().isin(YES)])
    print(f"{n} AI cards in the built-in deck (mobile/src/game/promoted.ts)")


if __name__ == "__main__":
    main()
